/** Arabic has six plural forms; these texts do not change with the number, so all six say the same. */
function plural(key: string, text: string): Record<string, string> {
  return Object.fromEntries(["zero", "one", "two", "few", "many", "other"].map((form) => [`${key}_${form}`, text]));
}

